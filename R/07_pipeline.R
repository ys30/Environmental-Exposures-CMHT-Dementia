# Confidential-data pipeline. Run ONLY inside an approved secure environment.
# Input path is supplied via CRIS_ANALYSIS_INPUT; never store patient records in Git.
source("R/00_config.R")
source("R/01_cohort_and_variables.R")
source("R/08_model_engine.R")
source("R/09_sensitivity.R")
source("R/10_export.R")
check_packages(c("MASS", "sandwich", "lmtest"))
input <- Sys.getenv("CRIS_ANALYSIS_INPUT", unset = "")
if (!nzchar(input) || !file.exists(input)) stop("Set CRIS_ANALYSIS_INPUT to an authorized local .rds file")
if (tolower(tools::file_ext(input)) != "rds") stop("Input must be an .rds file")
dat <- readRDS(input)
if (!is.data.frame(dat)) stop("Input must contain a data.frame")
dir.create("results/private", recursive = TRUE, showWarnings = FALSE)
spec <- get_model_spec(dat)
output <- run_all_models(dat, spec)
saveRDS(output, "results/private/model_results.rds")
write_private_results(output, "results/private")
message("Complete. Outputs remain private; disclosure review required.")
